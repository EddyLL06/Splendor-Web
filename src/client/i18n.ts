const storedLanguage = (): SupportedLanguage => {
  if (typeof window === 'undefined') return 'en';
  return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'zh-CN'
    ? 'zh-CN'
    : 'en';
};

void i18n.use(initReactI18next).init({
  resources: translations,
  lng: storedLanguage(),
  fallbackLng: 'en',
  supportedLngs: ['en', 'zh-CN'],
  interpolation: { escapeValue: false },
  returnNull: false,
});

export const setLanguage = async (language: SupportedLanguage): Promise<void> => {
  window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  document.documentElement.lang = language;
  document.title = translations[language].translation.common.appName;
  await i18n.changeLanguage(language);
};

if (typeof document !== 'undefined') {
  const language = storedLanguage();
  document.documentElement.lang = language;
  document.title = translations[language].translation.common.appName;
}

export default i18n;
